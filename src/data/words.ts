export function getDifficultyForScore(score: number): DifficultyLevelInfo {
  for (let i = DIFFICULTY_LEVELS.length - 1; i >= 0; i--) {
    if (score >= DIFFICULTY_LEVELS[i].minScore) {
      if (i === DIFFICULTY_LEVELS.length - 1 && score > 4800) {
        const extraLevels = Math.floor((score - 4800) / 2500);
        if (extraLevels > 0) {
          return {
            ...DIFFICULTY_LEVELS[i],
            level: 5 + extraLevels,
            titleEn: `Level ${5 + extraLevels} · Champion +${extraLevels}`,
            titleTh: `ระดับ ${5 + extraLevels} · แชมป์คำศัพท์ ขั้นสุด`,
            speedMultiplier: Number((1.5 + extraLevels * 0.08).toFixed(2)),
            baseSpeed: Math.min(28, 23 + extraLevels * 1.2),
            obstacleGapMin: Math.max(20, 24 - extraLevels),
            obstacleGapMax: Math.max(26, 31 - extraLevels),
          };
        }
      }
      return DIFFICULTY_LEVELS[i];
    }
  }
  return DIFFICULTY_LEVELS[0];
}

export function formatPlaytime(totalSeconds: number): string {
  const secs = Math.max(0, Math.floor(totalSeconds));
  const hours = Math.floor(secs / 3600);
  const minutes = Math.floor((secs % 3600) / 60);
  const remainingSeconds = secs % 60;

  const pad = (n: number) => String(n).padStart(2, '0');
  if (hours > 0) {
    return `${hours}:${pad(minutes)}:${pad(remainingSeconds)}`;
  }
  return `${pad(minutes)}:${pad(remainingSeconds)}`;
}

export function getRandomWord(
  difficulty?: 'easy' | 'medium' | 'hard',
  excludedIds: string[] = []
): WordEntry {
  let pool = VOCABULARY_LIST.filter((w) => !excludedIds.includes(w.id));
  if (difficulty) {
    const diffPool = pool.filter((w) => w.difficulty === difficulty);
    if (diffPool.length > 0) pool = diffPool;
  }
  if (pool.length === 0) pool = VOCABULARY_LIST;
  return pool[Math.floor(Math.random() * pool.length)];
}
